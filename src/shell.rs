use crate::Result;
/// Shell integration - generates hooks for different shells
use std::fmt;

/// Supported shell types
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ShellType {
    Zsh,
    Bash,
    // Future: Fish, PowerShell
}

impl fmt::Display for ShellType {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            ShellType::Zsh => write!(f, "zsh"),
            ShellType::Bash => write!(f, "bash"),
        }
    }
}

/// Shell hook generator
pub struct ShellHook {
    shell_type: ShellType,
}

impl ShellHook {
    /// Create a new shell hook generator
    pub fn new(shell_type: ShellType) -> Self {
        Self { shell_type }
    }

    /// Generate the shell hook code
    pub fn generate(&self) -> String {
        match self.shell_type {
            ShellType::Zsh => self.generate_zsh(),
            ShellType::Bash => self.generate_bash(),
        }
    }

    /// Generate Zsh hook code
    fn generate_zsh(&self) -> String {
        r#"
# Omniscient - Command History Tracker
# Generated by: omniscient init
# Add this to your ~/.zshrc

# The hook needs zsh/datetime for $EPOCHREALTIME. Load it here rather than
# assuming a framework did: without it the timer is empty, and a hook that makes
# capture conditional on its timer then records nothing at all, silently.
# zmodload is idempotent and costs nothing on a shell that already has it.
zmodload zsh/datetime 2>/dev/null

# Capture the command as the shell received it.
#
# preexec is handed the command line in $1. precmd must NOT read it back from
# history: SHARE_HISTORY imports other sessions before each prompt and can
# return a command typed in another terminal, HIST_IGNORE_SPACE keeps
# space-prefixed commands out of history entirely so the previous command gets
# recorded twice, and a fresh shell has no history to read at all.
_omniscient_preexec() {
    _OMNISCIENT_CMD=$1
    _OMNISCIENT_RAN=1
    _OMNISCIENT_START=${EPOCHREALTIME:-}
}

# Capture command after execution
_omniscient_precmd() {
    local exit_code=$?

    # Guard on "a command ran", never on the timer. A missing duration is a
    # degraded record; a missing command is a lost one.
    [[ -n "$_OMNISCIENT_RAN" ]] || return

    # Truncate with parameter expansion rather than int(), which needs
    # zsh/mathfunc — another module the hook cannot assume. A float here would
    # make --duration unparseable and the capture would be discarded.
    local duration=0
    if [[ -n "$_OMNISCIENT_START" && -n "${EPOCHREALTIME:-}" ]]; then
        duration=${$(( (EPOCHREALTIME - _OMNISCIENT_START) * 1000 ))%%.*}
        [[ $duration == <-> ]] || duration=0
    fi

    # Run capture in background to avoid blocking shell
    # Redirect output and disown to prevent job notifications
    omniscient capture --exit-code "$exit_code" --duration "$duration" "$_OMNISCIENT_CMD" &>/dev/null &!

    unset _OMNISCIENT_START _OMNISCIENT_CMD _OMNISCIENT_RAN
}

# Register hooks with Zsh
precmd_functions+=(_omniscient_precmd)
preexec_functions+=(_omniscient_preexec)

# Optional: Set up completion (future enhancement)
# autoload -Uz compinit
# compinit
"#
        .to_string()
    }

    /// Generate Bash hook code
    fn generate_bash(&self) -> String {
        r#"
# Omniscient - Command History Tracker
# Generated by: omniscient init
# Add this to your ~/.bashrc (Linux) or ~/.bash_profile (macOS)

# NOTE: Requires bash-preexec library
# Install with:
# curl -sSL https://github.com/rcaloras/bash-preexec/raw/master/bash-preexec.sh -o ~/.bash-preexec.sh
# Then add to your bash profile: source ~/.bash-preexec.sh

# Milliseconds since the epoch, best effort.
#
# Nanosecond formats from date(1) are not portable: BSD date (macOS) does not
# implement them and emits a literal trailing "N", which then fails bash
# arithmetic with "value too great for base" and takes the whole capture down
# with it. bash 5 provides $EPOCHREALTIME built in; where it is absent there is
# no sub-second clock worth a dependency, so report 0 and still record the
# command.
_omniscient_now_ms() {
    if [[ -n "${EPOCHREALTIME:-}" ]]; then
        local secs=${EPOCHREALTIME%%[.,]*}
        local frac=${EPOCHREALTIME##*[.,]}
        frac=${frac}000
        # 10# forces base 10; a leading zero would otherwise be read as octal.
        printf '%s' "$(( secs * 1000 + 10#${frac:0:3} ))"
    else
        printf '0'
    fi
}

# Capture the command as the shell received it.
#
# bash-preexec hands preexec the command line in $1. Reading it back from the
# history builtin in precmd is unreliable for the same reasons it is in zsh, and
# returns nothing at all in a shell that has not run a command yet.
_omniscient_preexec() {
    _OMNISCIENT_CMD="$1"
    _OMNISCIENT_RAN=1
    _OMNISCIENT_START=$(_omniscient_now_ms)
}

# Capture command after execution
_omniscient_precmd() {
    local exit_code=$?

    # Guard on "a command ran", never on the timer.
    if [[ -n "${_OMNISCIENT_RAN:-}" ]]; then
        local duration=0
        local end
        end=$(_omniscient_now_ms)
        if [[ "$_OMNISCIENT_START" != "0" && "$end" != "0" ]]; then
            duration=$(( end - _OMNISCIENT_START ))
            (( duration < 0 )) && duration=0
        fi

        # Run capture in background to avoid blocking shell
        # Redirect output and disown to prevent job notifications
        omniscient capture --exit-code "$exit_code" --duration "$duration" "$_OMNISCIENT_CMD" &>/dev/null &
        disown

        unset _OMNISCIENT_START _OMNISCIENT_CMD _OMNISCIENT_RAN
    fi
}

# Register hooks with bash-preexec
preexec_functions+=(_omniscient_preexec)
precmd_functions+=(_omniscient_precmd)
"#
        .to_string()
    }

    /// Whether an omniscient hook is present in the user's shell startup files.
    ///
    /// Worth asking, because the most complete capture failure is the one where
    /// no hook was ever installed: nothing errors, nothing is logged, and the
    /// database simply stays empty.
    pub fn installed_in(files: &[std::path::PathBuf]) -> Option<std::path::PathBuf> {
        files.iter().find(|f| {
            std::fs::read_to_string(f)
                .map(|c| c.contains("_omniscient_precmd"))
                .unwrap_or(false)
        }).cloned()
    }

    /// The startup files a shell would load a hook from.
    pub fn candidate_rc_files() -> Vec<std::path::PathBuf> {
        let home = match std::env::var("HOME") {
            Ok(h) => std::path::PathBuf::from(h),
            Err(_) => return Vec::new(),
        };
        let zdotdir = std::env::var("ZDOTDIR").ok().map(std::path::PathBuf::from);
        let base = zdotdir.unwrap_or_else(|| home.clone());
        vec![
            base.join(".zshrc"),
            base.join(".zshenv"),
            base.join(".zprofile"),
            home.join(".bashrc"),
            home.join(".bash_profile"),
        ]
    }

    /// Auto-detect the current shell
    pub fn detect_shell() -> Result<ShellType> {
        // Check $SHELL environment variable
        if let Ok(shell) = std::env::var("SHELL") {
            if shell.contains("zsh") {
                return Ok(ShellType::Zsh);
            } else if shell.contains("bash") {
                return Ok(ShellType::Bash);
            }
        }

        // Default to Zsh if detection fails
        Ok(ShellType::Zsh)
    }

    /// Get installation instructions for the shell
    pub fn installation_instructions(&self) -> String {
        match self.shell_type {
            ShellType::Zsh => {
                r#"Installation Instructions for Zsh:

1. Run this command to generate the hook:
   omniscient init

2. Add the output to your ~/.zshrc file:
   omniscient init >> ~/.zshrc

3. Reload your shell:
   source ~/.zshrc

4. Start using your shell normally - all commands will be captured automatically!

To verify it's working:
   omniscient stats

Optional: Export your history before setup to preserve existing data.
"#
                .to_string()
            }
            ShellType::Bash => {
                r#"Installation Instructions for Bash:

1. Install bash-preexec (required dependency):
   curl -sSL https://github.com/rcaloras/bash-preexec/raw/master/bash-preexec.sh -o ~/.bash-preexec.sh

2. Add bash-preexec to your shell profile:
   # For Linux (add to ~/.bashrc):
   echo 'source ~/.bash-preexec.sh' >> ~/.bashrc

   # For macOS (add to ~/.bash_profile):
   echo 'source ~/.bash-preexec.sh' >> ~/.bash_profile

3. Generate and add Omniscient hook:
   # For Linux:
   omniscient init --shell bash >> ~/.bashrc

   # For macOS:
   omniscient init --shell bash >> ~/.bash_profile

4. Reload your shell:
   # For Linux:
   source ~/.bashrc

   # For macOS:
   source ~/.bash_profile

5. Start using your shell normally - all commands will be captured automatically!

To verify it's working:
   omniscient stats

Optional: Export your history before setup to preserve existing data.
"#
                .to_string()
            }
        }
    }
}

impl Default for ShellHook {
    fn default() -> Self {
        Self::new(ShellType::Zsh)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_shell_hook_creation() {
        let hook = ShellHook::new(ShellType::Zsh);
        assert_eq!(hook.shell_type, ShellType::Zsh);
    }

    #[test]
    fn test_zsh_hook_generation() {
        let hook = ShellHook::new(ShellType::Zsh);
        let code = hook.generate();

        // Verify essential components are present
        assert!(code.contains("_omniscient_preexec"));
        assert!(code.contains("_omniscient_precmd"));
        assert!(code.contains("EPOCHREALTIME"));
        assert!(code.contains("precmd_functions+="));
        assert!(code.contains("preexec_functions+="));
        assert!(code.contains("omniscient capture"));
        assert!(code.contains("&")); // Background execution
        // The command text comes from preexec's argument. Reading it back from
        // history is defeated by SHARE_HISTORY, HIST_IGNORE_SPACE and an empty
        // history — see tests/shell/ for each case.
        assert!(code.contains("_OMNISCIENT_CMD=$1"));
        assert!(!code.contains("fc -ln"));
    }

    #[test]
    fn test_hook_has_error_handling() {
        let hook = ShellHook::new(ShellType::Zsh);
        let code = hook.generate();

        // Capture is guarded on "a command ran", never on the timer. Guarding
        // on the clock means a shell without zsh/datetime records nothing at
        // all, silently — see tests/shell/no_datetime.zsh.
        assert!(code.contains("[[ -n \"$_OMNISCIENT_RAN\" ]] || return"));
        assert!(!code.contains("[[ -n \"$_OMNISCIENT_START\" ]] || return"));

        // Should clean up its state
        assert!(code.contains("unset _OMNISCIENT_START"));
        assert!(code.contains("_OMNISCIENT_RAN"));
    }

    #[test]
    fn test_hook_async_execution() {
        let hook = ShellHook::new(ShellType::Zsh);
        let code = hook.generate();

        // Verify async execution (background process)
        assert!(code.contains("&"));
        assert!(code.contains("omniscient capture"));
    }

    #[test]
    fn test_installation_instructions() {
        let hook = ShellHook::new(ShellType::Zsh);
        let instructions = hook.installation_instructions();

        assert!(instructions.contains("omniscient init"));
        assert!(instructions.contains("~/.zshrc"));
        assert!(instructions.contains("source"));
    }

    #[test]
    fn test_shell_type_display() {
        assert_eq!(ShellType::Zsh.to_string(), "zsh");
        assert_eq!(ShellType::Bash.to_string(), "bash");
    }

    #[test]
    fn test_default_shell_hook() {
        let hook = ShellHook::default();
        assert_eq!(hook.shell_type, ShellType::Zsh);
    }

    // Bash-specific tests
    #[test]
    fn test_bash_hook_creation() {
        let hook = ShellHook::new(ShellType::Bash);
        assert_eq!(hook.shell_type, ShellType::Bash);
    }

    #[test]
    fn test_bash_hook_generation() {
        let hook = ShellHook::new(ShellType::Bash);
        let code = hook.generate();

        // Verify essential components are present
        assert!(code.contains("_omniscient_preexec"));
        assert!(code.contains("_omniscient_precmd"));
        // Timing comes from bash 5's built-in clock, not from a date(1) flag
        // that BSD does not implement.
        assert!(code.contains("_omniscient_now_ms"));
        assert!(code.contains("EPOCHREALTIME"));
        // The command text comes from preexec's argument, never from the
        // history builtin — see the zsh test for why.
        assert!(code.contains("_OMNISCIENT_CMD=\"$1\""));
        assert!(!code.contains("history 1"));
        assert!(code.contains("preexec_functions+="));
        assert!(code.contains("precmd_functions+="));
        assert!(code.contains("omniscient capture"));
        assert!(code.contains("&")); // Background execution
        assert!(code.contains("disown")); // Bash disown
    }

    #[test]
    fn test_bash_hook_has_bash_preexec_note() {
        let hook = ShellHook::new(ShellType::Bash);
        let code = hook.generate();

        // Should mention bash-preexec dependency
        assert!(code.contains("bash-preexec"));
    }

    #[test]
    fn test_bash_hook_has_error_handling() {
        let hook = ShellHook::new(ShellType::Bash);
        let code = hook.generate();

        // Capture is guarded on "a command ran", never on the timer. Guarding
        // on the clock means a shell with no sub-second source records nothing
        // at all — see tests/shell/no_subsecond_clock.sh.
        assert!(code.contains("[[ -n \"${_OMNISCIENT_RAN:-}\" ]]"));
        assert!(!code.contains("[[ -n \"$_OMNISCIENT_START\" ]]"));

        // Should clean up its state
        assert!(code.contains("unset _OMNISCIENT_START"));
        assert!(code.contains("_OMNISCIENT_RAN"));
    }

    #[test]
    fn test_bash_installation_instructions() {
        let hook = ShellHook::new(ShellType::Bash);
        let instructions = hook.installation_instructions();

        assert!(instructions.contains("bash-preexec"));
        assert!(instructions.contains("~/.bashrc"));
        assert!(instructions.contains("~/.bash_profile"));
        assert!(instructions.contains("omniscient init --shell bash"));
        assert!(instructions.contains("source"));
    }

    #[test]
    fn test_bash_hook_captures_all_required_data() {
        let hook = ShellHook::new(ShellType::Bash);
        let code = hook.generate();

        // Verify all required data is captured
        assert!(code.contains("exit_code")); // Exit code
        assert!(code.contains("duration")); // Duration
        assert!(code.contains("cmd")); // Command text
        assert!(code.contains("--exit-code"));
        assert!(code.contains("--duration"));
    }

    #[test]
    fn test_hook_captures_all_required_data() {
        let hook = ShellHook::new(ShellType::Zsh);
        let code = hook.generate();

        // Verify all required data is captured
        assert!(code.contains("exit_code")); // Exit code
        assert!(code.contains("duration")); // Duration
        assert!(code.contains("cmd")); // Command text
        assert!(code.contains("--exit-code"));
        assert!(code.contains("--duration"));
    }
}
